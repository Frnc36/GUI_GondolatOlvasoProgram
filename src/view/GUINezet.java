    public void kirak(String[] tomb) {
        StringBuilder sb = new StringBuilder();
        sb.append("1.\t2.\t3.\n");
        for (int i = 1; i < tomb.length; i++) {
            sb.append(tomb[i]).append("\t");
            if (i % 3 == 0) {
                sb.append("\n");
            }
        }
        jTextArea1.setText(sb.toString());
    }

