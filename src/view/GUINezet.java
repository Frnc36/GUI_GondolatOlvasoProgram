    public void kirak(Lap[] lapok) {
        StringBuilder sb = new StringBuilder();
        sb.append("1.\t2.\t3.\n");
        for (int i = 1; i < lapok.length; i++) {
            sb.append(lapok[i].megjelenit()).append("\t");
            if (i % 3 == 0) {
                sb.append("\n");
            }
        }
        jTextArea1.setText(sb.toString());
    }

